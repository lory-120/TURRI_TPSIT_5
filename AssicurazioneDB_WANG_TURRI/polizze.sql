DROP DATABASE IF EXISTS assicurazioni;
CREATE DATABASE assicurazioni;
USE assicurazioni;

DROP TABLE IF EXISTS clienti;
DROP TABLE IF EXISTS polizze;
DROP TABLE IF EXISTS pagamenti;

CREATE TABLE clienti (
  `id_cliente` varchar(6) NOT NULL,
  `cognome` varchar(35) DEFAULT NULL,
  `nome` varchar(50) DEFAULT NULL,
  `email` varchar(25) DEFAULT NULL,
  `telefono` varchar(16) DEFAULT NULL,
  `indirizzo` varchar(35) DEFAULT NULL,
  `cap` varchar(5) DEFAULT NULL,
  `citta` varchar(35) DEFAULT NULL,
  `provincia` varchar(2) DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE polizze (
  `id_polizza` varchar(6) NOT NULL,
  `id_cliente` varchar(6) DEFAULT NULL,
  `dt_inizio` date DEFAULT NULL,
  `dt_estinzione` date DEFAULT NULL,
  `periodicita` varchar(1) DEFAULT NULL,
  `premio_annuo` double DEFAULT NULL,
  `descrizione` varchar(50) DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE pagamenti (
  `id_pagamento` int(11) NOT NULL,
  `id_polizza` varchar(6) DEFAULT NULL,
  `dt_scadenza` date DEFAULT NULL,
  `dt_pagamento` date DEFAULT NULL,
  `importo` double DEFAULT NULL,
  `note` varchar(50) DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;


ALTER TABLE clienti
  ADD PRIMARY KEY (`id_cliente`);

ALTER TABLE pagamenti
  ADD PRIMARY KEY (`id_pagamento`),
  ADD KEY `Polizze_Pagamenti` (`id_polizza`);

ALTER TABLE polizze
  ADD PRIMARY KEY (`id_polizza`),
  ADD KEY `Clienti_Polizze` (`id_cliente`);
  

ALTER TABLE pagamenti
  MODIFY `id_pagamento` int(11) NOT NULL AUTO_INCREMENT, AUTO_INCREMENT=235;


ALTER TABLE pagamenti
  ADD CONSTRAINT `Polizze_Pagamenti` FOREIGN KEY (`id_polizza`) REFERENCES `polizze` (`id_polizza`);

ALTER TABLE polizze
  ADD CONSTRAINT `Clienti_Polizze` FOREIGN KEY (`id_cliente`) REFERENCES `clienti` (`id_cliente`);
  
  





